import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=x=>readFileSync(x,"utf8");
const publicRoute=read("src/app/page.tsx");
assert.ok(publicRoute.includes('components/templates/real-estate-home'),"Real estate home should be a template, not generic router code");
const preset=read("src/lib/site-presentation.ts");
assert.ok(preset.includes("organization")&&preset.includes("nexus"));
const genericBrand=read("src/components/site-brand.tsx");
assert.ok(!genericBrand.includes("REAL ESTATE")&&!genericBrand.includes("NEXUS"),"Generic brand must not contain NEXUS branding constants");
const nav=read("src/components/site-nav.tsx");
assert.ok(nav.includes("SiteBrand")&&nav.includes("presentation.contactAction"));
const footer=read("src/components/site-footer.tsx");
assert.ok(footer.includes("presentation.footerTitle")&&footer.includes("presentation.contactRegion"));
assert.ok(!footer.includes('> Nicaragua</span>'),"Region must not be forced for all clients");
const layout=read("src/app/layout.tsx");
assert.match(layout,/export async function generateMetadata/);
assert.ok(layout.includes("tenantFromHost"),"SEO metadata should resolve host-bound organization");
assert.ok(!layout.includes("Nexus Real Estate"),"Generic metadata must not hardcode first customer's brand");
console.log("Template boundaries, tenant branding and host-bound metadata checked.");
