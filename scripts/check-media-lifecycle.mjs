import assert from "node:assert/strict";
import {existsSync} from "node:fs";
import {readdir,stat,utimes} from "node:fs/promises";
import {join,resolve} from "node:path";
import {homedir} from "node:os";
import sharp from "sharp";

const origin=process.env.TEST_ORIGIN||"http://localhost:3000";
assert.equal(new URL(origin).hostname,"localhost","Use only CI localhost, never production");
const loginData=new FormData();
loginData.set("email",process.env.ADMIN_EMAIL||"");
loginData.set("password",process.env.ADMIN_PASSWORD||"");
const login=await fetch(origin+"/api/admin/session",{method:"POST",headers:{Origin:origin},body:loginData,redirect:"manual"});
assert.equal(login.status,303);
const cookie=login.headers.getSetCookie().find(x=>x.startsWith("webappecloud_session="))?.split(";")[0];
assert.ok(cookie);
const auth={Origin:origin,Cookie:cookie};
const postJSON=(action,slug,id,confirm,headers={...auth,"Content-Type":"application/json"})=>
 fetch(origin+"/api/admin/media/manage",{method:"POST",headers,
  body:JSON.stringify({action,slug,id,confirm}),redirect:"manual"});
const get=async path=>fetch(origin+path,{headers:{Cookie:cookie},redirect:"manual"});
const png=await sharp({create:{width:640,height:480,channels:3,background:"#3b728d"}}).png().toBuffer();
const form=new FormData();
form.set("image",new Blob([png],{type:"image/png"}),"lib-test.png");
const upload=await fetch(origin+"/api/admin/site-pages/home/images",{method:"POST",headers:auth,body:form});
const uploaded=await upload.json();
assert.equal(upload.status,200,JSON.stringify(uploaded));
const {id}=uploaded;assert.match(id,/^[a-f0-9]{32}$/);
const lib=await (await get("/api/admin/media")).json();
assert.ok(lib.items.some(x=>x.slug==="home"&&x.id===id&&x.recent&&!x.used&&!x.canArchive),"New image must be protected");
const url="/api/admin/site-pages/home/images/"+id;
const recently=await postJSON("archive","home",id,"ARCHIVAR");
assert.equal(recently.status,409,"Recent image must not be archivable");
const csrf=await postJSON("archive","home",id,"ARCHIVAR",{Cookie:cookie,Origin:"https://unauthorized.invalid","Content-Type":"application/json"});
assert.equal(csrf.status,403,"Trash mutations require same-origin");
const noConfirm=await postJSON("archive","home",id);
assert.equal(noConfirm.status,400,"Archive must require explicit confirmation");
// Match the application default: media persists outside the Git deployment directory.
const config=resolve(process.env.APP_CONFIG_DIR||join(homedir(),"nexus-runtime"));
const tenants=await readdir(join(config,"page-images"));
let tenantId="";
for(const value of tenants){
 if(existsSync(join(config,"page-images",value,"home",id+".webp"))){tenantId=value;break;}
}
assert.ok(tenantId,"Could not locate test media inside CI config dir");
const live=join(config,"page-images",tenantId,"home",id+".webp");
const trash=join(config,"page-images-trash",tenantId,"home",id+".webp");
const age=async(path,days)=>{const date=new Date(Date.now()-days*86400000);await utimes(path,date,date);};
await age(live,2);
const eligible=await (await get("/api/admin/media")).json();
assert.ok(eligible.items.some(x=>x.slug==="home"&&x.id===id&&x.canArchive),"Old unused image must be flagged");
const section={id:"section-trashing-test",type:"image",imageId:id,alt:"Imagen de prueba para proteger una página",caption:""};
const save=async sections=>{
 const f=new FormData();f.set("sections",JSON.stringify(sections));
 return fetch(origin+"/api/admin/site-extras/home",{method:"POST",headers:auth,body:f,redirect:"manual"});
};
assert.match((await save([section])).headers.get("location")||"",/blocksSaved=1/);
const used=await (await get("/api/admin/media")).json();
assert.ok(used.items.some(x=>x.slug==="home"&&x.id===id&&x.used&&!x.canArchive),"Referenced media must be marked in use");
const protectedMedia=await postJSON("archive","home",id,"ARCHIVAR");
assert.equal(protectedMedia.status,409,"Referenced media must never be archived");
assert.equal((await get(url)).status,200);
await save([]);
const archived=await postJSON("archive","home",id,"ARCHIVAR");
assert.equal(archived.status,200,await archived.text());
assert.equal((await get(url)).status,404,"Live file must leave gallery after archiving");
const privateTrash="/api/admin/media/trash/home/"+id;
assert.equal((await get(privateTrash)).status,200,"Admin must be able to preview trash");
const anonymous=await fetch(origin+privateTrash,{redirect:"manual"});
assert.ok([303,307,308,401,403].includes(anonymous.status),"Trash preview must require login");
const trashListing=await (await get("/admin/personalizar/medios")).text();
assert.ok(trashListing.includes("Biblioteca de imágenes"),"Gallery unavailable");
const tooEarly=await postJSON("purge","home",id,"ELIMINAR");
assert.equal(tooEarly.status,409,"At least seven days retention required");
const restored=await postJSON("restore","home",id);
assert.equal(restored.status,200,"Restoration must work");
assert.equal((await get(url)).status,200,"Restored media must be accessible to editor");
assert.equal((await get(privateTrash)).status,404);
await age(live,2);
const archivedAgain=await postJSON("archive","home",id,"ARCHIVAR");
assert.equal(archivedAgain.status,200);
const trashStat=await stat(trash);
assert.ok(Date.now()-trashStat.mtimeMs<3600000,"Trash retention must start at archive, not original upload");
await age(trash,8);
assert.equal((await postJSON("purge","home",id)).status,400,"Permanent delete requires explicit confirmation");
assert.equal((await postJSON("purge","home",id,"ELIMINAR")).status,200,"Aged archived image can be permanently deleted");
assert.equal((await get(privateTrash)).status,404);
assert.equal((await get(url)).status,404);
const badPage=await postJSON("archive","site-navigation",id,"ARCHIVAR");
assert.equal(badPage.status,404,"Internal CMS pages are not manageable media");
console.log("CMS media lifecycle: recent protection, references, CSRF, archive, seven-day trash, restore and purge passed.");
