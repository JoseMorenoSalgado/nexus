import assert from "node:assert/strict";
import {readFileSync,existsSync} from "node:fs";
const read=p=>readFileSync(p,"utf8");
const registry=read("src/lib/site-template-registry.ts");
const modules=read("src/lib/tenant-modules-registry.ts");
const page=read("src/app/admin/(panel)/personalizar/plantilla/page.tsx");
const installer=read("src/components/installer-form.tsx");
assert.match(registry,/key:"real-estate"/);
assert.ok(!/key:"education"|key:"ecommerce"|key:"services"/.test(registry));
assert.ok(!/key:"moodle"|key:"billing"|key:"catalog"|key:"orders"/.test(modules));
assert.ok(!existsSync("src/components/templates/organization-site.tsx"),"No generic-sector storefront");
assert.ok(!existsSync("src/components/template-gallery.tsx"),"No sector-switcher gallery");
assert.match(page,/redirect\("\/admin\/personalizar\/inicio"\)/,"La pantalla informativa antigua debe abrir Mi sitio web");
assert.ok(!page.includes("TemplateGallery"));
assert.ok(!installer.includes("SITE_TEMPLATES.map"),"Installer must not offer other business categories");
assert.ok(installer.includes('templateKey:"real-estate"'));
assert.ok(read("src/lib/site-pages.ts").includes('id:"asesoria-empresarial"'),"Keep client-requested advisory page");
console.log("NEXUS: only real estate offered, advisory retained and no sector switchers.");
