import assert from "node:assert/strict";
import sharp from "sharp";
import {execFileSync} from "node:child_process";
const origin=process.env.TEST_ORIGIN||"http://localhost:3000";
assert.equal(new URL(origin).hostname,"localhost","Only isolated CI services supported");
const loginForm=new FormData();
loginForm.set("email",process.env.ADMIN_EMAIL||"");loginForm.set("password",process.env.ADMIN_PASSWORD||"");
const login=await fetch(origin+"/api/admin/session",{method:"POST",headers:{Origin:origin},body:loginForm,redirect:"manual"});
assert.equal(login.status,303);
const cookie=login.headers.getSetCookie().find(x=>x.startsWith("webappecloud_session="))?.split(";")[0];
assert.ok(cookie);
const headers={Origin:origin,Cookie:cookie};
const post=async(path,form,custom=headers)=>fetch(origin+path,{method:"POST",headers:custom,body:form,redirect:"manual"});
const get=async path=>fetch(origin+path,{headers:{Cookie:cookie}});
const makeSections=sections=>{const f=new FormData();f.set("sections",JSON.stringify(sections));return f;};
const home="/api/admin/site-extras/home";
const extrasEdit=await get("/admin/personalizar/paginas/home");
assert.equal(extrasEdit.status,200);
const initial=await extrasEdit.text();
assert.match(initial,/Secciones adicionales/);
const before=await (await fetch(origin+"/")).text();
assert.match(before,/nexus-hero-layout-simple/);
const altered=await post(home,makeSections([{id:"section-home-example",type:"heading",text:"Más información en nuestro sitio"}]));
assert.match(altered.headers.get("location")||"",/blocksSaved=1/);
const after=await (await fetch(origin+"/")).text();
assert.ok(after.includes("Más información en nuestro sitio"),"Extra section not published on home");
assert.ok(after.includes("nexus-hero-layout-simple"),"Original branded home structure changed");
const bad=await post(home,makeSections([{id:"section-malformed",type:"image",imageId:"f".repeat(32),alt:"Imagen de ejemplo",caption:""}]));
assert.match(bad.headers.get("location")||"",/error=imagenes/,"Missing media should not be saved");
const source=await sharp({create:{width:1200,height:700,channels:3,background:"#6792a2"}}).png().toBuffer();
const f=new FormData();f.set("image",new Blob([source],{type:"image/png"}),"imagen-de-prueba.png");
const up=await post("/api/admin/site-pages/home/images",f);
const upBody=await up.json();
assert.equal(up.status,200,"Builtin upload failed "+JSON.stringify(upBody));
const id=upBody.id;
assert.match(id,/^[a-f0-9]{32}$/);
assert.equal((await fetch(origin+"/api/site-page-images/home/"+id)).status,404,"Unreferenced page image must not be public");
const library=await get("/api/admin/media");
assert.equal(library.status,200);
const listing=await library.json();
assert.ok(listing.items.some(x=>x.slug==="home"&&x.id===id),"Uploaded image not shown in library");
const gallery=await get("/admin/personalizar/medios");
assert.equal(gallery.status,200);
const galleryHtml=await gallery.text();
assert.ok(galleryHtml.includes("Biblioteca de imágenes")&&galleryHtml.includes("/api/admin/site-pages/home/images/"+id),"Media gallery not usable");
const anonGallery=await fetch(origin+"/admin/personalizar/medios",{redirect:"manual"});
assert.ok([303,307,308].includes(anonGallery.status),"Library must be private");
const forged=await fetch(origin+"/api/admin/media/import",{method:"POST",headers:{Cookie:cookie,Origin:"https://evil.invalid","Content-Type":"application/json"},body:JSON.stringify({sourceSlug:"home",targetSlug:"nosotros",imageId:id})});
assert.equal(forged.status,403);
const imported=await fetch(origin+"/api/admin/media/import",{method:"POST",headers:{...headers,"Content-Type":"application/json"},body:JSON.stringify({sourceSlug:"home",targetSlug:"nosotros",imageId:id})});
const importedValue=await imported.json();
assert.equal(imported.status,200,JSON.stringify(importedValue));
assert.match(importedValue.id,/^[a-f0-9]{32}$/);
assert.notEqual(importedValue.id,id);
const pageImage={id:"section-picture-02",type:"image",imageId:importedValue.id,alt:"Fotografía de prueba para la página Nosotros",caption:"Imagen reutilizada"};
const saveAbout=await post("/api/admin/site-extras/nosotros",makeSections([pageImage]));
assert.match(saveAbout.headers.get("location")||"",/blocksSaved=1/);
const publicPic="/api/site-page-images/nosotros/"+importedValue.id;
const response=await fetch(origin+publicPic);
assert.equal(response.status,200);
assert.equal(response.headers.get("content-type"),"image/webp");
const about=(await (await fetch(origin+"/nosotros")).text());
assert.ok(about.includes("Imagen reutilizada"),"Reusable image not displayed on builtin page");
const cross=execFileSync("curl",["-sS","-o","/dev/null","-w","%{http_code}","-H","Host: unauthorized-tenant.invalid",origin+publicPic],{encoding:"utf8"}).trim();
assert.equal(cross,"404","Media accessible to unauthorized host");
const status=new FormData();status.set("intent","status");
await post("/api/admin/site-pages/nosotros",status);
assert.equal((await fetch(origin+publicPic)).status,404,"Draft media must be private");
status.set("published","on");
await post("/api/admin/site-pages/nosotros",status);
assert.equal((await fetch(origin+publicPic)).status,200);
await post(home,makeSections([]));await post("/api/admin/site-extras/nosotros",makeSections([]));
assert.equal((await fetch(origin+publicPic)).status,404,"Removed media reference still served publicly");
const restored=await (await fetch(origin+"/")).text();
assert.ok(!restored.includes("Más información en nuestro sitio"),"Test content not removed");
assert.match(restored,/nexus-hero-layout-simple/);
console.log("Builtin page extras and tenant image library: saved, displayed, private, restored and isolated.");
