import assert from "node:assert/strict";
const origin=process.env.TEST_ORIGIN||"http://localhost:3000";
assert.equal(new URL(origin).hostname,"localhost");
const credentials=new FormData();credentials.set("email",process.env.ADMIN_EMAIL);credentials.set("password",process.env.ADMIN_PASSWORD);
const login=await fetch(origin+"/api/admin/session",{method:"POST",headers:{Origin:origin},body:credentials,redirect:"manual"});
assert.equal(login.status,303);
const cookie=login.headers.getSetCookie().find(c=>c.startsWith("webappecloud_session="))?.split(";")[0];
assert.ok(cookie);
const get=async(path)=>{const r=await fetch(origin+path,{headers:{Cookie:cookie}});assert.equal(r.status,200,path+" should load");return r.text();};
const pages=await get("/admin/personalizar/paginas");
assert.ok(pages.includes("Nueva página")&&pages.includes("Buscar páginas"),"CMS list controls absent");
assert.ok(pages.includes("cms-page-table")&&pages.includes("cms-toolbar"),"CMS compact UI missing");
const newEditor=await get("/admin/personalizar/paginas/nueva");
for(const name of ["title","slug","summary","body","published"])assert.ok(newEditor.includes('name="'+name+'"'),"Missing new page field "+name);
assert.ok(newEditor.includes("Vista previa")&&newEditor.includes("Sin publicar"),"Page preview must be identified as unpublished");
assert.ok(newEditor.includes("Crear página"),"New page submit missing");
const about=await get("/admin/personalizar/paginas/nosotros");
assert.ok(about.includes("cms-field")&&about.includes("Gestio")&&about.includes('name="aboutMission"'),"About editor polish missing");
const home=await get("/admin/personalizar/paginas/home");
assert.ok(home.includes('name="heroHeading"')&&!home.includes('name="servicesHeading"'),"Home editor contains another page's content");
const services=await get("/admin/personalizar/paginas/servicios");
assert.ok(services.includes('name="servicesSale"')&&!services.includes('name="aboutVision"'),"Services editor mixed with About");
const menu=await get("/admin/personalizar/menu");
assert.ok(menu.includes("Así se verá el menú")&&menu.includes("Deshacer cambios"),"Menu preview/reset missing");
const afterCreate=await get("/admin/personalizar/paginas/guia-inmobiliaria-ci");
assert.ok(afterCreate.includes("Vista previa")&&afterCreate.includes('name="published"'),"Saved custom page editor not modernized");
const anonymous=await fetch(origin+"/admin/personalizar/paginas/nueva",{redirect:"manual"});
assert.ok([303,307,308].includes(anonymous.status),"Anonymous page editor exposure");
console.log("CMS polish: compact index, new page form, unsaved preview, isolated editors, menu preview and auth passed.");
